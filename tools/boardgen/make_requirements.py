"""Stage `requirements` (P2-T9): evaluate netlist.py's REQUIREMENTS against the design IR + electrical model.

    python tools/boardgen/make_requirements.py <project-id>

Reads projects/<id>/out/design.json (the `ir` stage; its `requirements` section is netlist.py's REQUIREMENTS), judges each
one with req/eval.py, prints one line per requirement, writes projects/<id>/out/REQUIREMENTS.md (PASS / FAIL /
NOT_EVALUATED / ERROR table, deterministic) and the findings to $PCB_FINDINGS_FILE.  Exit 1 on any FAIL or ERROR (a
malformed requirement: unknown ref / pin / net / kind).  NOT_EVALUATED is shown and counted, never PASS, and does not fail
a hand board (P2-T10's release gate blocks `pcba` on it).  A project with 0 requirements: WARN (hand) / ERROR (pcba).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))                      # tools/
from boardgen import project as _project                       # noqa: E402
from boardgen.elec.model import build_model                     # noqa: E402
from boardgen.req import eval as _eval                          # noqa: E402
from boardgen.rules.finding import Finding                      # noqa: E402
from boardgen.rules import engine as _engine                    # noqa: E402

RULE = "REQ"


def _fmt_measured(m):
    if m is None:
        return ""
    if isinstance(m, (list, tuple)):
        return "%.4g..%.4g" % (m[0], m[1])
    return "%.4g" % m


def render_md(pid, results, mode):
    sm = _eval.summary(results)
    out = ["# Requirements: %s" % pid, "",
           "Generated by `tools/boardgen/make_requirements.py` from `REQUIREMENTS` in `projects/%s/gen/netlist.py`. Do not edit." % pid, "",
           "**%d PASS, %d FAIL, %d NOT_EVALUATED, %d ERROR** (%d requirements; assembly: %s)." % (
               sm["PASS"], sm["FAIL"], sm["NOT_EVALUATED"], sm["ERROR"], len(results), mode or "undeclared"), "",
           "NOT_EVALUATED means the engine lacked the data to judge it - it is never a pass and blocks a `pcba` release.", "",
           "| Id | Kind | Requirement | Result | Evidence / reason |", "|---|---|---|---|---|"]
    for r in results:
        detail = r["why"] if r["result"] != "PASS" else r["evidence"]
        if r["result"] == "FAIL" and r["evidence"]:
            detail = "%s  [%s]" % (r["why"], r["evidence"])
        m = _fmt_measured(r["measured"])
        if m and r["result"] != "PASS":
            detail += "  (measured %s)" % m
        out.append("| %s | %s | %s | **%s** | %s |" % (r["id"], r["kind"] or "?", r["text"].replace("|", "/"), r["result"],
                                                    (detail or "").replace("|", "/").replace("\n", " ")))
    return "\n".join(out) + "\n"


def main(argv):
    pid = _project.project_id_from_argv(["x"] + argv[1:])
    if not pid:
        raise SystemExit("usage: make_requirements.py <project-id>")
    path = os.path.join(_project.PROJECTS, pid, "out", "design.json")
    if not os.path.isfile(path):
        print("FAILED: %s missing - run the `ir` stage first" % path)
        return 1
    with open(path, encoding="utf-8") as f:
        ir = json.load(f)
    mode = (ir.get("assembly") or {}).get("mode")
    results = _eval.evaluate(ir, build_model(ir))
    findings = []
    for r in results:
        print("%-13s %-4s %-12s %s%s" % (r["result"], r["id"], r["kind"] or "?", r["text"],
                                         ("  -> " + (r["why"] or r["evidence"])) if r["result"] != "PASS" else ""))
        where = {}
        if r["result"] == "PASS":
            continue
        sev = "NOT_JUDGED" if r["result"] == "NOT_EVALUATED" else "ERROR"
        findings.append(Finding("REQ-%s" % r["id"], sev, "%s: %s" % (r["text"], r["why"]), where=where, target=r["id"],
                                fix="fix netlist.py, or the requirement if the design intent changed"))
    if not results:
        sev = "ERROR" if mode == "pcba" else "WARN"
        findings.append(Finding("REQ-NONE", sev, "the board has nothing to be checked against: netlist.py has no REQUIREMENTS", target="REQUIREMENTS"))
        print("%s REQ-NONE: no REQUIREMENTS in netlist.py" % sev)
    sm = _eval.summary(results)
    stats = {RULE: {"examined": len(results), "judged": sm["PASS"] + sm["FAIL"], "not_judged": sm["NOT_EVALUATED"],
                    "errors": sm["FAIL"] + sm["ERROR"], "waived": 0}}
    out_dir = os.path.join(_project.PROJECTS, pid, "out")
    with open(os.path.join(out_dir, "REQUIREMENTS.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write(render_md(pid, results, mode))
    out_path = os.environ.get("PCB_FINDINGS_FILE")
    if out_path:
        _engine.write_findings(out_path, findings, stats)
    print("\nrequirements: %d PASS, %d FAIL, %d NOT_EVALUATED, %d ERROR -> projects/%s/out/REQUIREMENTS.md" % (
        sm["PASS"], sm["FAIL"], sm["NOT_EVALUATED"], sm["ERROR"], pid))
    if sm["FAIL"] or sm["ERROR"] or any(f.severity == "ERROR" for f in findings):
        print("FAILED: %d requirement(s) failed or malformed" % (sm["FAIL"] + sm["ERROR"] or 1))
        return 1
    print("requirements OK: %s" % pid)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
